#pragma once

// страница это любой экран: меню, вход, регистрация и тд
// методы:
//   render() - рисует экран
//   next()   - читает ввод, возвращает следующую страницу
// что возвращает next():
//   другая страница - переход на неё
//   this - перерисовка
//   nullptr - всё, приложение закрывается
// страницы создаются один раз в main, живут до конца,
// эта функция только переключает между ними
class Page {
public:
    virtual void render() = 0;   // рисует экран
    virtual Page* next() = 0;    // ввод + следующая страница
    virtual ~Page() = default;   // чтобы корректно удалять по Page*
};

// эта строчка запускает цикл страниц: рисует, читает ввод, переключает
// крутится, пока next() не вернёт nullptr
inline void runPages(Page* start) {
    Page* current = start;
    while (current != nullptr) {
        current->render();         // рисует текущую страницу
        current = current->next(); // читает ввод и переключает
    }
}